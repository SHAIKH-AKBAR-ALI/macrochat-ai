export type UIKey = keyof (typeof ui)["en"];

/** Translator bound to one locale, English as the fallback. */
export function useT(lang: Locale) {
  return (key: UIKey): string =>
    (ui[lang] as Record<string, string>)[key] ?? ui[DEFAULT_LOCALE][key];
}
